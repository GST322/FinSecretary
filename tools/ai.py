import random

def ask_ai(question: str) -> str:
    q = question.lower()
    
    # База знаний псевдонейросети (весовые триггеры)
    if any(word in q for word in ['портфель', 'актив', 'инвестиц', 'анализ']):
        responses = [
            "Ваш портфель сбалансирован. Рекомендую удерживать текущие позиции и следить за дивидендными выплатами.",
            "Анализ показывает умеренный риск. Рассмотрите возможность ребалансировки в сторону облигаций.",
            "Портфель выглядит стабильно. Основные драйверы роста сохранены, волатильность в пределах нормы."
        ]
        return random.choice(responses)
        
    elif any(word in q for word in ['совет', 'что делать', 'купить', 'продать']):
        return "Как финансовый секретарь, я рекомендую не поддаваться эмоциональным решениям. Следуйте вашей долгосрочной стратегии и усредняйте позиции при просадках."
        
    elif any(word in q for word in ['привет', 'здравствуй', 'как дела']):
        return "Здравствуйте! Я ваш финансовый секретарь. Готов проанализировать ваш портфель или оценить новость."
        
    else:
        return "Я проанализировал ваш запрос. На текущий момент рыночная конъюнктура нейтральна. Рекомендую сохранять денежную позицию и наблюдать за новостным фоном."